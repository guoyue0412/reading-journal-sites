import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contentRoot = path.join(root, "content");
const outputPath = path.join(root, "lib/content/generated.ts");
const modules = ["jobs", "internship", "papers", "reflections"];

function parseScalar(raw) {
  const value = raw.trim();
  if (value.startsWith("[") && value.endsWith("]")) {
    const body = value.slice(1, -1).trim();
    return body ? body.split(",").map((item) => parseScalar(item)) : [];
  }
  if (/^-?\d+(?:\.\d+)?$/.test(value)) return Number(value);
  if (value === "true") return true;
  if (value === "false") return false;
  if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) return value.slice(1, -1);
  return value;
}

function parseMarkdown(source, filePath) {
  const match = source.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!match) throw new Error(`Missing frontmatter: ${filePath}`);
  const metadata = {};
  for (const line of match[1].split(/\r?\n/)) {
    if (!line.trim() || line.trimStart().startsWith("#")) continue;
    const separator = line.indexOf(":");
    if (separator < 1) throw new Error(`Invalid frontmatter line in ${filePath}: ${line}`);
    metadata[line.slice(0, separator).trim()] = parseScalar(line.slice(separator + 1));
  }
  return { ...metadata, body: match[2].trim() };
}

function validateEntry(entry, moduleName, filePath) {
  for (const key of ["title", "slug", "type", "date", "summary", "tags", "related", "status"]) {
    if (entry[key] === undefined || entry[key] === "") throw new Error(`Missing ${key}: ${filePath}`);
  }
  if (entry.type !== moduleName) throw new Error(`Type ${entry.type} does not match ${moduleName}: ${filePath}`);
  if (!Array.isArray(entry.tags) || !Array.isArray(entry.related)) throw new Error(`tags and related must be arrays: ${filePath}`);
  if (!["draft", "published"].includes(entry.status)) throw new Error(`Invalid status: ${filePath}`);
  if (entry.type === "reflections" && entry.slug !== entry.date) throw new Error(`Reflection slug must match date: ${filePath}`);
}

async function collectEntries() {
  const entries = [];
  const slugs = new Set();
  for (const moduleName of modules) {
    const directory = path.join(contentRoot, moduleName);
    const files = (await fs.readdir(directory)).filter((file) => file.endsWith(".md")).sort();
    for (const file of files) {
      const filePath = path.join(directory, file);
      const entry = parseMarkdown(await fs.readFile(filePath, "utf8"), filePath);
      validateEntry(entry, moduleName, filePath);
      if (slugs.has(entry.slug)) throw new Error(`Duplicate slug: ${entry.slug}`);
      slugs.add(entry.slug);
      entries.push(entry);
    }
  }
  for (const entry of entries) {
    for (const relatedSlug of entry.related) {
      if (!slugs.has(relatedSlug)) console.warn(`Unresolved related slug "${relatedSlug}" in "${entry.slug}"`);
    }
  }
  return entries;
}

const entries = await collectEntries();
const generated = `// Generated by scripts/generate-content-index.mjs. Do not edit.\nimport type { ContentEntry } from "./types";\n\nexport const CONTENT_ENTRIES: ContentEntry[] = ${JSON.stringify(entries, null, 2)};\n`;
await fs.mkdir(path.dirname(outputPath), { recursive: true });
await fs.writeFile(outputPath, generated, "utf8");
console.log(`Generated ${entries.length} content entries.`);
